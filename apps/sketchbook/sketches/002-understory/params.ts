import { defineSchema, param } from '@mytw/schema'

const TAU = Math.PI * 2

const CENTER_Y_HELP =
	'Measured up from the bottom of the image (the buffer is drawn with a Y-flip). A project uses 1 − value.'
const FADE_HELP =
	'The ghost is fully visible at the fade start and gone by the fade end (screen Y, 0 is the bottom). Swap the two to invert.'

/** Understory's parameters. Defaults reproduce the original hard-coded look. */
export const understorySchema = defineSchema(
	{
		// Loop
		fps: param.integer({
			label: 'FPS',
			default: 30,
			min: 1,
			max: 120,
			unit: 'fps',
			group: 'Loop',
		}),
		loopFrames: param.integer({
			label: 'Loop frames',
			default: 225,
			min: 2,
			max: 900,
			unit: 'frames',
			group: 'Loop',
			help: "Master speed. More frames is slower motion. 225 at 30 fps is a 7.5 s loop, under Spotify Canvas's 8 s limit.",
		}),

		// Motion, shared by both layers
		driftAmp: param.number({
			label: 'Drift amplitude',
			default: 0.012,
			min: 0,
			max: 0.2,
			unit: 'UV',
			group: 'Motion',
			help: 'Travel radius. Smaller is slower and covers less distance.',
		}),
		ghostScale: param.number({
			label: 'Ghost travel',
			default: 0.8,
			min: 0,
			max: 1,
			group: 'Motion',
			help: "Fraction of the base's travel the ghost covers.",
		}),
		ghostContrary: param.boolean({
			label: 'Ghost contrary',
			default: false,
			group: 'Motion',
			help: 'Off: the ghost drifts with the base. On: it drifts the opposite way.',
		}),
		driftCyclesX: param.integer({
			label: 'Drift cycles X',
			default: 1,
			min: 0,
			max: 8,
			loopSafe: true,
			group: 'Motion',
			help: 'X oscillations per loop.',
		}),
		driftCyclesY: param.integer({
			label: 'Drift cycles Y',
			default: 1,
			min: 0,
			max: 8,
			loopSafe: true,
			group: 'Motion',
			help: 'Y oscillations per loop. Unequal X and Y trace a figure eight.',
		}),
		driftPhase: param.number({
			label: 'Drift phase',
			default: 0,
			min: 0,
			max: TAU,
			unit: 'rad',
			group: 'Motion',
		}),
		spin: param.integer({
			label: 'Spin',
			default: 0,
			min: -4,
			max: 4,
			loopSafe: true,
			unit: 'turns',
			group: 'Motion',
			help: 'Whole turns per loop. 0 is off.',
		}),
		wobbleAmp: param.number({
			label: 'Wobble amplitude',
			default: 0,
			min: 0,
			max: 0.5,
			unit: 'rad',
			group: 'Motion',
		}),
		wobbleCycles: param.integer({
			label: 'Wobble cycles',
			default: 1,
			min: 0,
			max: 8,
			loopSafe: true,
			group: 'Motion',
		}),
		wobblePhase: param.number({
			label: 'Wobble phase',
			default: 0,
			min: 0,
			max: TAU,
			unit: 'rad',
			group: 'Motion',
		}),
		breatheAmp: param.number({
			label: 'Breathe amplitude',
			default: 0.022,
			min: 0,
			max: 0.2,
			group: 'Motion',
			help: 'Shared in-and-out scale pulse. Both layers breathe together.',
		}),
		breatheCycles: param.integer({
			label: 'Breathe cycles',
			default: 1,
			min: 0,
			max: 8,
			loopSafe: true,
			group: 'Motion',
			help: 'Breaths per loop.',
		}),
		breathePhase: param.number({
			label: 'Breathe phase',
			default: 0,
			min: 0,
			max: TAU,
			unit: 'rad',
			group: 'Motion',
		}),

		// Base layer framing
		baseZoom: param.number({
			label: 'Zoom',
			default: 2,
			min: 1,
			max: 8,
			group: 'Base',
			help: 'Tighter crop. Keep it high enough that drift and breathe stay edge-free.',
		}),
		baseCenterX: param.number({
			label: 'Center X',
			default: 0.5,
			min: 0,
			max: 1,
			group: 'Base',
		}),
		baseCenterY: param.number({
			label: 'Center Y',
			default: 0.72,
			min: 0,
			max: 1,
			group: 'Base',
			help: CENTER_Y_HELP,
		}),
		baseMirrorX: param.boolean({ label: 'Mirror X', default: false, group: 'Base' }),
		baseMirrorY: param.boolean({ label: 'Mirror Y', default: false, group: 'Base' }),
		baseTilt: param.number({
			label: 'Tilt',
			default: 0,
			min: -Math.PI,
			max: Math.PI,
			unit: 'rad',
			group: 'Base',
		}),

		// Ghost layer framing and rotation
		ghostZoom: param.number({
			label: 'Zoom',
			default: 3.4,
			min: 1,
			max: 8,
			group: 'Ghost',
		}),
		ghostCenterX: param.number({
			label: 'Center X',
			default: 0.2,
			min: 0,
			max: 1,
			group: 'Ghost',
		}),
		ghostCenterY: param.number({
			label: 'Center Y',
			default: 0.25,
			min: 0,
			max: 1,
			group: 'Ghost',
			help: CENTER_Y_HELP,
		}),
		ghostMirrorX: param.boolean({
			label: 'Mirror X',
			default: true,
			group: 'Ghost',
			help: "Flips the ghost so its bright cluster lands opposite the base's.",
		}),
		ghostMirrorY: param.boolean({ label: 'Mirror Y', default: false, group: 'Ghost' }),
		ghostTilt: param.number({
			label: 'Tilt',
			default: 0,
			min: -Math.PI,
			max: Math.PI,
			unit: 'rad',
			group: 'Ghost',
		}),
		ghostSpin: param.integer({
			label: 'Spin',
			default: 0,
			min: -4,
			max: 4,
			loopSafe: true,
			unit: 'turns',
			group: 'Ghost',
			help: 'Whole turns per loop. 0 is off.',
		}),
		ghostWobbleAmp: param.number({
			label: 'Wobble amplitude',
			default: 0.03,
			min: 0,
			max: 0.5,
			unit: 'rad',
			group: 'Ghost',
			help: 'Rotational sway. Any amount stays seamless.',
		}),
		ghostWobbleCycles: param.integer({
			label: 'Wobble cycles',
			default: 1,
			min: 0,
			max: 8,
			loopSafe: true,
			group: 'Ghost',
			help: 'Sways per loop.',
		}),
		ghostWobblePhase: param.number({
			label: 'Wobble phase',
			default: 0,
			min: 0,
			max: TAU,
			unit: 'rad',
			group: 'Ghost',
		}),
		ghostFadeStart: param.number({
			label: 'Fade start',
			default: 0,
			min: 0,
			max: 1,
			group: 'Ghost',
			help: FADE_HELP,
		}),
		ghostFadeEnd: param.number({
			label: 'Fade end',
			default: 1,
			min: 0,
			max: 1,
			group: 'Ghost',
			help: FADE_HELP,
		}),

		// Look
		intensity: param.number({
			label: 'Intensity',
			default: 1,
			min: 0,
			max: 1,
			group: 'Look',
			help: 'Multiply strength. 0 shows the base only.',
		}),
		vignette: param.number({
			label: 'Vignette',
			default: 0.2,
			min: 0,
			max: 1,
			group: 'Look',
			help: '0 is off, 1 is strong edge darkening.',
		}),
		feather: param.number({
			label: 'Feather',
			default: 0.06,
			min: 0,
			max: 0.25,
			unit: 'UV',
			group: 'Look',
			help: "Soft falloff at each layer's edges.",
		}),
		hueShift: param.number({
			label: 'Hue shift',
			default: -15,
			min: -180,
			max: 180,
			unit: '°',
			group: 'Look',
			help: 'Negative is toward green, positive toward blue.',
		}),

		// Caustic shimmer
		causticAmp: param.number({
			label: 'Amount',
			default: 0.005,
			min: 0,
			max: 0.05,
			unit: 'UV',
			group: 'Caustic',
			help: 'Shared warp, like looking through moving water. 0 is off.',
		}),
		causticScale: param.number({
			label: 'Scale',
			default: 2,
			min: 0.1,
			max: 10,
			group: 'Caustic',
			help: 'Noise frequency. Higher is finer ripples.',
		}),
		causticLoopRadius: param.number({
			label: 'Loop radius',
			default: 0.8,
			min: 0,
			max: 4,
			group: 'Caustic',
			help: "Radius of the noise's circular loop path.",
		}),

		// Chromatic aberration
		aberrationBase: param.number({
			label: 'Base',
			default: 0.001,
			min: 0,
			max: 0.05,
			unit: 'UV',
			group: 'Aberration',
			help: 'Constant RGB split at the edges.',
		}),
		aberrationPulseAmp: param.number({
			label: 'Pulse amount',
			default: 0.01,
			min: 0,
			max: 0.05,
			unit: 'UV',
			group: 'Aberration',
			help: 'Extra split added at each pulse peak.',
		}),
		aberrationPulseCycles: param.integer({
			label: 'Pulse cycles',
			default: 1,
			min: 0,
			max: 8,
			loopSafe: true,
			group: 'Aberration',
			help: 'Pulses per loop.',
		}),
		aberrationPulsePhase: param.number({
			label: 'Pulse phase',
			default: 0,
			min: 0,
			max: TAU,
			unit: 'rad',
			group: 'Aberration',
		}),
	},
	{
		constraints: [
			{
				id: 'base-edge-free',
				params: ['baseZoom', 'driftAmp'],
				message:
					'Base zoom must be at least 1 / (1 − 2 × drift amplitude), or the base shows its edges',
				check: (v) => v.baseZoom * (1 - 2 * v.driftAmp) >= 1,
			},
			{
				id: 'ghost-edge-free',
				params: ['ghostZoom', 'driftAmp'],
				message:
					'Ghost zoom must be at least 1 / (1 − 2 × drift amplitude), or the ghost shows its edges',
				check: (v) => v.ghostZoom * (1 - 2 * v.driftAmp) >= 1,
			},
			{
				id: 'ghost-fade-span',
				params: ['ghostFadeStart', 'ghostFadeEnd'],
				message: 'Ghost fade start and end must differ',
				check: (v) => v.ghostFadeStart !== v.ghostFadeEnd,
			},
		],
	}
)
